package core

import (
	"context"
	"errors"
	"fmt"
	"os"
)

func validateSetupContent(ctx context.Context, runner CommandRunner, binary, dataDir, staging string, content []byte) (resultErr error) {
	file, err := os.CreateTemp(staging, "setup-config-*.yaml")
	if err != nil {
		return err
	}
	path := file.Name()
	defer func() {
		if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
			resultErr = errors.Join(resultErr, fmt.Errorf("remove setup config candidate: %w", err))
		}
	}()
	if err := file.Chmod(0o600); err != nil {
		return errors.Join(err, file.Close())
	}
	if _, err := file.Write(content); err != nil {
		return errors.Join(err, file.Close())
	}
	if err := file.Close(); err != nil {
		return err
	}
	return ValidateConfig(ctx, runner, binary, dataDir, path)
}

// ValidateCandidateConfig validates fresh Manager-generated bytes with the exact
// protected core candidate, without executing the old installed core.
func (t *TrustedExecution) ValidateCandidateConfig(ctx context.Context, prepared PreparedCore, content []byte) (resultErr error) {
	candidate, ok := prepared.(*Candidate)
	if !ok {
		return dataFailure("protected core candidate unavailable for validation")
	}
	verified, err := candidate.Verified(ctx)
	if err != nil {
		return err
	}
	defer func() { resultErr = errors.Join(resultErr, verified.Close()) }()
	configuration, err := t.files.prepare(ctx, content)
	if err != nil {
		return err
	}
	defer func() {
		resultErr = errors.Join(resultErr, t.files.remove(context.WithoutCancel(ctx), configuration), configuration.Close())
	}()
	return ValidateVerifiedConfig(ctx, verified, configuration, t.executor)
}
